//! Colormap LUT + normalization helpers.
//!
//! Hardcoded 256-row viridis (the matplotlib default). Add more
//! colormaps behind the same `&str` switch (`magma`, `inferno`, etc.)
//! when the demand is real.

pub type Lut = [[u8; 3]; 256];

/// Pick a LUT by name. Falls back to viridis for unknown names — a
/// warning at the SQL boundary is the caller's job.
pub fn lookup(name: &str) -> &'static Lut {
    match name.to_ascii_lowercase().as_str() {
        "viridis" => &VIRIDIS,
        _ => &VIRIDIS,
    }
}

/// `t ∈ [0, 1]` → RGB byte triple. Linear-interps between adjacent LUT
/// rows. NaN / out-of-range t is clamped.
pub fn sample(lut: &Lut, t: f32) -> [u8; 3] {
    if !t.is_finite() {
        return lut[0];
    }
    let t = t.clamp(0.0, 1.0);
    let scaled = t * 255.0;
    let lo = scaled.floor() as usize;
    let hi = (lo + 1).min(255);
    let frac = scaled - (lo as f32);
    let a = lut[lo];
    let b = lut[hi];
    [
        lerp(a[0], b[0], frac),
        lerp(a[1], b[1], frac),
        lerp(a[2], b[2], frac),
    ]
}

#[inline]
fn lerp(a: u8, b: u8, t: f32) -> u8 {
    let f = a as f32 + (b as f32 - a as f32) * t;
    f.round().clamp(0.0, 255.0) as u8
}

/// Map `value` into `[0, 1]` using `vmin`/`vmax`. NaN → 0; zero-range
/// → 0 to avoid Inf. Caller is responsible for vmin < vmax in normal
/// cases.
pub fn normalize(value: f64, vmin: f64, vmax: f64) -> f32 {
    if !value.is_finite() {
        return 0.0;
    }
    let range = vmax - vmin;
    if range.abs() < f64::EPSILON {
        return 0.0;
    }
    ((value - vmin) / range) as f32
}

