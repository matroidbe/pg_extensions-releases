#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sample_endpoints_match_lut() {
        let v0 = sample(&VIRIDIS, 0.0);
        let v1 = sample(&VIRIDIS, 1.0);
        assert_eq!(v0, VIRIDIS[0]);
        assert_eq!(v1, VIRIDIS[255]);
    }

    #[test]
    fn sample_clamps_out_of_range() {
        let v_neg = sample(&VIRIDIS, -0.5);
        let v_big = sample(&VIRIDIS, 1.5);
        assert_eq!(v_neg, VIRIDIS[0]);
        assert_eq!(v_big, VIRIDIS[255]);
    }

    #[test]
    fn sample_nan_returns_zero_row() {
        let v = sample(&VIRIDIS, f32::NAN);
        assert_eq!(v, VIRIDIS[0]);
    }

    #[test]
    fn normalize_basics() {
        assert_eq!(normalize(0.0, 0.0, 10.0), 0.0);
        assert_eq!(normalize(10.0, 0.0, 10.0), 1.0);
        assert_eq!(normalize(5.0, 0.0, 10.0), 0.5);
        assert_eq!(normalize(f64::NAN, 0.0, 10.0), 0.0);
        // Zero-range: not Inf, must be 0.
        assert_eq!(normalize(7.0, 5.0, 5.0), 0.0);
    }

    #[test]
    fn lookup_unknown_falls_back_to_viridis() {
        // Rust doesn't dedupe addresses of `const` references, so compare
        // by content (endpoints) rather than pointer identity.
        let lut = lookup("does-not-exist");
        assert_eq!(lut[0], VIRIDIS[0]);
        assert_eq!(lut[255], VIRIDIS[255]);
    }
}
